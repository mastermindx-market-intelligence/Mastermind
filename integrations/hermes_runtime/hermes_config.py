"""Write the disarmed Hermes profile the qualified preflight already accepts."""
from __future__ import annotations

import hashlib
import re

from .constants import QUALIFIED_VISION_ROUTE, REFUSED_HERMES_TOOLSETS
from .errors import RuntimeRefusal
from .profile import RuntimeProfile

_SAFE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}$")


def render_hermes_config(profile: RuntimeProfile) -> str:
    if profile.hermes_allowlist != frozenset({"clarify"}):
        raise RuntimeRefusal("HERMES_ALLOWLIST_NOT_CLARIFY")
    provider = profile.model_provider
    default = profile.model_default
    vision_provider = QUALIFIED_VISION_ROUTE["provider"]
    vision_model = QUALIFIED_VISION_ROUTE["model"]
    for token in (provider, default, vision_provider, vision_model):
        if not isinstance(token, str) or not _SAFE.fullmatch(token):
            raise RuntimeRefusal("UNQUALIFIED_MODEL_ROUTE")
    disabled = "\n".join(f"    - {name}" for name in sorted(REFUSED_HERMES_TOOLSETS))
    return (
        "# Generated by integrations.hermes_runtime. No secrets.\n"
        "model:\n"
        f"  provider: {provider}\n"
        f"  default: {default}\n"
        "auxiliary:\n"
        "  vision:\n"
        f"    provider: {vision_provider}\n"
        f"    model: {vision_model}\n"
        "agent:\n"
        "  disabled_toolsets:\n"
        f"{disabled}\n"
        "toolsets:\n"
        "  - clarify\n"
    )


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()
