_SNAPSHOT_MODULES = (
    "portfolio/decision_snapshot.py",
    "portfolio/decision_snapshot_sources.py",
    "portfolio/decision_snapshot_contracts.py",
    "scripts/portfolio_decision_snapshot.py",
)

# Settlement writers, the pending-target/fill write-back surfaces, and the allocation
# submission writer: none of them may appear in a snapshot module's imports.
_FORBIDDEN_IMPORT_SUBSTRINGS = (
    "settlement",
    "pending",
    "paper_account",
    "trade_history",
    "position_log",
    "decision_submission",
    "fill_pending",
    "reset_book",
    "bridge",
)

_REPO_ROOT = Path(__file__).resolve().parent.parent


def _module_trees() -> dict:
    return {
        name: ast.parse((_REPO_ROOT / name).read_text(encoding="utf-8"))
        for name in _SNAPSHOT_MODULES
    }


def _imported_names(tree) -> set:
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.module:
                names.add(node.module)
            names.update(
                f"{node.module}.{alias.name}" if node.module else alias.name
                for alias in node.names
            )
    return names


def _registry_attribute_uses(tree) -> set:
    """Every ``registry.<attr>`` access in a module's AST."""
    attrs = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id == "registry"
        ):
            attrs.add(node.attr)
    return attrs


def _fingerprint(root: Path) -> dict:
    return {
        str(path.relative_to(root)): (
            path.read_bytes(),
            path.stat().st_mtime_ns,
        )
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def test_compose_is_read_only_and_isolated(journey_root):
    _stage_book()
    book_tree_before = _fingerprint(sources._ROOT)

    created = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    assert created["snapshot_id"].startswith("sha256:")

    # Every staged book file is byte- and mtime-identical after composition.
    assert _fingerprint(sources._ROOT) == book_tree_before

    # Nothing was created outside the fixed shadow snapshot directory: the only entries
    # under the storage root are the literal directory chain to the leaf and the leaf
    # itself — no sibling file or directory anywhere along the way.
    leaf = snapshots.snapshot_dir("autonomous")
    assert leaf == journey_root / "data" / "shadow" / "decision_snapshots" / "autonomous"
    assert any(leaf.glob("*.json"))
    allowed_chain = {
        "data",
        "data/shadow",
        "data/shadow/decision_snapshots",
        "data/shadow/decision_snapshots/autonomous",
    }
    for path in journey_root.rglob("*"):
        rel = path.relative_to(journey_root).as_posix()
        assert rel in allowed_chain or rel.startswith(
            "data/shadow/decision_snapshots/autonomous/"
        ), path

    # AST: the four snapshot modules import no settlement, pending-target-writer, or
    # registry-mutating surface.
    trees = _module_trees()
    for name, tree in trees.items():
        imported = _imported_names(tree)
        offending = sorted(
            full for full in imported
            if any(token in full.lower() for token in _FORBIDDEN_IMPORT_SUBSTRINGS)
        )
        assert offending == [], (name, offending)

    # The registry use that does exist is read-only: ``registry.data_dir(book)`` is the
    # allowlisted, fail-closed path resolver (portfolio/registry.py, ``data_dir``) that
    # returns the book's canonical relative layout; decision_snapshot_sources re-roots
    # that relative path under its own ``_ROOT`` (``_book_dir``) and never writes through
    # it, and the accompanying ``getattr(registry, "_ROOT", ...)`` only reads the registry
    # repo root for that same relative-path arithmetic.
    registry_uses = set()
    for tree in trees.values():
        registry_uses |= _registry_attribute_uses(tree)
    assert registry_uses <= {"data_dir", "_ROOT"}
    assert "data_dir" in registry_uses
