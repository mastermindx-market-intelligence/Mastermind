# Journey 2: the byte bound discriminates — old tail law cannot seal this book
# ---------------------------------------------------------------------------

def test_byte_bounded_tail_discriminates(journey_root, capsys):
    _stage_book()

    # Old law (row-count-only tail): 95 x ~10 KB decision rows reach the seal unbounded and
    # ``create_snapshot`` dies on the 262144-byte snapshot limit. New law: it seals.
    sealed = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    assert sealed["snapshot_id"].startswith("sha256:")
    assert len(canonical_json_bytes(sealed)) <= c.MAX_SNAPSHOT_BYTES

    sizes = {
        section_id: len(canonical_json_bytes(section))
        for section_id, section in sealed["sections"].items()
    }
    print("SECTION_CANONICAL_BYTES " + json.dumps(sizes, sort_keys=True))
    assert set(sizes) == set(c.SECTION_IDS)
    assert all(size <= c.MAX_SNAPSHOT_BYTES for size in sizes.values())

    # Unit: newest-first retention under the byte budget, oldest→newest return order.
    rows = [{"i": i} for i in range(10)]  # oldest → newest on disk
    raw = b"".join(canonical_json_bytes(row) + b"\n" for row in rows)
    tail = sources._parse_jsonl_tail(raw, max_bytes=40)
    assert tail["error_code"] is None
    assert [row["i"] for row in tail["rows"]] == [6, 7, 8, 9]
    assert len(canonical_json_bytes(tail["rows"])) <= 40
    assert tail["rows_total"] == 10
    assert tail["rows_returned"] == 4
    assert tail["omitted_rows"] == 6

    # Unit: the row cap and the byte budget compose; every drop is counted omissions.
    capped = sources._parse_jsonl_tail(raw, max_rows=2, max_bytes=c.MAX_JSONL_TAIL_BYTES)
    assert [row["i"] for row in capped["rows"]] == [8, 9]
    assert capped["rows_total"] == 10
    assert capped["omitted_rows"] == 8

    # Unit: invalid lines keep the same omission arithmetic alongside the byte budget.
    mixed = (
        canonical_json_bytes(rows[0]) + b"\n"
        + b"{not valid json\n"
        + b"\n".join(canonical_json_bytes(row) for row in rows[1:]) + b"\n"
        + b"[also not an object]\n"
    )
    mixed_tail = sources._parse_jsonl_tail(mixed, max_bytes=40)
    assert mixed_tail["rows_total"] == 12
    assert mixed_tail["rows_returned"] == 4
    assert mixed_tail["omitted_rows"] == 8

    # Unit: one valid row that alone exceeds the budget is OVERSIZE, never a zero-row
    # COMPLETE claim — and at capture level it routes the source to the same fail-closed
    # OVERSIZE status a MAX_SOURCE_BYTES read overflow uses.
    oversize_tail = sources._parse_jsonl_tail(
        canonical_json_bytes({"memo": "x" * 200}) + b"\n", max_bytes=50,
    )
    assert oversize_tail["error_code"] == "OVERSIZE"
    assert oversize_tail["rows"] == []
    assert oversize_tail["rows_returned"] == 0
    assert oversize_tail["rows_total"] == 1
    assert oversize_tail["omitted_rows"] == 1

    _write_jsonl(_book_dir() / "decisions.jsonl", [{"memo": "synthetic " + "x" * 70_000}])
    _pin_mtime(_book_dir() / "decisions.jsonl")
    blocked = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    assert blocked["created"] is True
    oversize_receipt = _receipts(blocked)["book.decisions"]
    assert oversize_receipt["status"] == "OVERSIZE"
    assert oversize_receipt["error_code"] == "OVERSIZE"
    assert oversize_receipt["coverage_state"] == "BLOCKED"
    assert blocked["sections"]["historical_memory"]["coverage_state"] == "BLOCKED"
    assert blocked["state"] != "COMPLETE"


