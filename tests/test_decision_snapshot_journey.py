"""Journey-level tests for the byte-bounded, snapshot→inspector Decision Snapshot flow.

Synthetic, shape-faithful data only: every row, ticker, and memo below is generated by
this file. The book mirrors the real production shape (many ~10 KB decision rows, a fill
blotter, a pending target, a positions ledger, no account.json) without copying any byte
of any captured production file.

Journey, not unit coverage: compose a realistic oversized book end-to-end, project it
through ``read_projection``/``latest_snapshot`` and the operator CLI, and prove the
fail-closed coverage laws survive (missing context, future-dated sources, forged bytes,
changed evidence, read-only isolation).
"""
