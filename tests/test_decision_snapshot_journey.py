# Journey 6: changed evidence at one cutoff mints a correction, original preserved
# ---------------------------------------------------------------------------

def test_changed_context_mints_correction_and_preserves_original(journey_root):
    _stage_book()
    original = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    original_path = snapshots._snapshot_path("autonomous", original["snapshot_id"])
    original_bytes = original_path.read_bytes()

    # Same content family, different pending target, mtime still <= the cutoff: the change
    # is eligible evidence, so a same-cutoff recompose must mint a CORRECTED generation.
    _write_json(_book_dir() / "pending_target.json", {
        "as_of": "2026-09-15",
        "note": "synthetic pending target REVISED for the journey book",
        "targets": [
            {"ticker": f"SYN{j:02d}", "weight": round(0.02 * (j + 1), 4)} for j in range(10)
        ],
    })
    _pin_mtime(_book_dir() / "pending_target.json")

    corrected = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at="2026-09-15T20:10:00Z",
    )
    assert corrected["created"] is True
    assert corrected["snapshot_id"] != original["snapshot_id"]
    assert corrected["correction"]["status"] == "CORRECTED"
    assert corrected["correction"]["same_cutoff_prior_snapshot_ids"] == [
        original["snapshot_id"]
    ]

    # Corrections are additive: the original stored bytes are untouched and still verify.
    assert original_path.read_bytes() == original_bytes
    preserved = snapshots.load_snapshot("autonomous", original["snapshot_id"])
    c.verify_snapshot(preserved)
    assert preserved["snapshot_id"] == original["snapshot_id"]


