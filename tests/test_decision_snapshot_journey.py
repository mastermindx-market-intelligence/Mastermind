_CUTOFF = "2026-09-15T20:00:00Z"
_RECORDED = "2026-09-15T20:01:00Z"


def _epoch(utc: str) -> int:
    parsed = datetime.strptime(utc, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    return int(parsed.timestamp())


_PRE_CUTOFF_EPOCH = _epoch("2026-09-15T19:00:00Z")
_FUTURE_EPOCH = _epoch("2026-09-15T20:05:00Z")


@pytest.fixture
def journey_root(tmp_path, monkeypatch):
    repo = tmp_path / "repo"
    macro = tmp_path / "macro"  # intentionally empty: every consumed context source absent
    storage = tmp_path / "storage"
    repo.mkdir()
    macro.mkdir()
    storage.mkdir()
    monkeypatch.setattr(sources, "_ROOT", repo)
    monkeypatch.setattr(sources, "_V", macro)
    monkeypatch.setattr(snapshots, "_ROOT", storage)
    return storage


def _book_dir() -> Path:
    return sources._ROOT / "data" / "portfolios" / "autonomous"


def _write_jsonl(path: Path, rows: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"".join(canonical_json_bytes(row) + b"\n" for row in rows))


def _write_json(path: Path, payload) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(json.dumps(payload, sort_keys=True).encode("utf-8"))


def _pin_mtime(path: Path, epoch: int = _PRE_CUTOFF_EPOCH) -> None:
    os.utime(path, (epoch, epoch))


# ---------------------------------------------------------------------------
# Synthetic, shape-faithful book (no captured byte is used anywhere below)
# ---------------------------------------------------------------------------

_MEMO_SENTENCE = "synthetic narrative filler sentence for the shape-faithful journey book. "
_SUMMARY_SENTENCE = "synthetic summary line one of many. "


def _decision_row(i: int) -> dict:
    return {
        "decision_id": f"decision.journey.{i:06d}",
        "asof": "2026-09-15",
        "run_id": f"journey-run-{i:06d}",
        "target_status": "synthetic",
        "holdings": [
            {
                "ticker": f"SYN{(i + j) % 40:02d}",
                "shares": 100 + i + j,
                "weight": round(0.001 * ((i * 7 + j) % 500 + 1), 4),
            }
            for j in range(8)
        ],
        "summary": _SUMMARY_SENTENCE * 40,
        "memo": f"synthetic decision {i:06d} memo. " + _MEMO_SENTENCE * 110,
    }


def _fill_row(i: int) -> dict:
    return {
        "transaction_id": f"journey-txn-{i:06d}",
        "asof": "2026-09-15",
        "ticker": f"SYN{i % 40:02d}",
        "side": "buy",
        "shares": 10 + (i % 90),
        "price": round(1.0 + (i % 50) * 0.25, 4),
    }


def _stage_book(*, decision_count: int = 95, fill_count: int = 95,
                mtime_epoch: int = _PRE_CUTOFF_EPOCH) -> None:
    """Stage the synthetic autonomous book: big decisions/fills JSONL tails, a pending
    target, a positions ledger — and deliberately NO account.json."""
    decisions = [_decision_row(i) for i in range(decision_count)]
    for row in decisions:
        # Shape-faithful ~10 KB rows: bound them so the byte-budget arithmetic below is
        # meaningful and stable across Python versions.
        assert 8_000 <= len(canonical_json_bytes(row)) <= 12_000
    _write_jsonl(_book_dir() / "decisions.jsonl", decisions)
    _write_jsonl(_book_dir() / "fills.jsonl", [_fill_row(i) for i in range(fill_count)])
    _write_json(_book_dir() / "pending_target.json", {
        "as_of": "2026-09-15",
        "note": "synthetic pending target for the journey book",
        "targets": [
            {"ticker": f"SYN{j:02d}", "weight": round(0.01 * (j + 1), 4)} for j in range(10)
        ],
    })
    _write_json(_book_dir() / "positions_ledger.json", {
        "as_of": "2026-09-15",
        "note": "synthetic positions ledger for the journey book",
        "entries": [
            {"ticker": f"SYN{j:02d}", "shares": 10 + j, "opened_asof": "2026-09-01"}
            for j in range(20)
        ],
    })
    for name in ("decisions.jsonl", "fills.jsonl", "pending_target.json",
                 "positions_ledger.json"):
        _pin_mtime(_book_dir() / name, mtime_epoch)
    assert not (_book_dir() / "account.json").exists()


def _receipts(snapshot: dict) -> dict:
    return {r["source_id"]: r for r in snapshot["sources"]}


# ---------------------------------------------------------------------------
# Journey 1: compose → project → CLI on a real-shaped book without an account
# ---------------------------------------------------------------------------

def test_journey_compose_project_cli_on_book_without_account(journey_root, capsys):
    _stage_book()

    created = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    assert created["snapshot_id"].startswith("sha256:")
    assert created["coverage_state"] != "COMPLETE"
    assert created["state"] != "COMPLETE"

    receipts = _receipts(created)
    # The required account is absent: MISSING source, BLOCKED book truth, sealed anyway.
    assert receipts["book.account"]["status"] == "MISSING"
    assert created["sections"]["book_truth"]["coverage_state"] == "BLOCKED"
    # The ~10 KB x 95 decision tail is byte-bounded: the newest rows that fit stay, the
    # rest are counted omissions — never silently truncated, never an unbounded snapshot.
    decisions = receipts["book.decisions"]
    assert decisions["status"] == "AVAILABLE"
    assert decisions["omitted_rows"] > 0
    assert decisions["rows_total"] == decisions["rows_returned"] + decisions["omitted_rows"]

    projection = snapshots.read_projection(
        "autonomous", snapshot_id=None, section_id=None, offset=0, limit=10,
    )
    assert projection["snapshot"]["snapshot_id"] == created["snapshot_id"]
    assert snapshots.latest_snapshot("autonomous")["snapshot_id"] == created["snapshot_id"]

    # Operator CLI read path over the same store: status and show both surface that id.
    assert cli.main(["status", "--book", "autonomous"]) == 0
    status_payload = json.loads(capsys.readouterr().out)
    assert status_payload["status"] == "OK"
    assert status_payload["manifest"]["snapshot_id"] == created["snapshot_id"]

    assert cli.main([
        "show", "--book", "autonomous", "--snapshot-id", created["snapshot_id"],
    ]) == 0
    show_payload = json.loads(capsys.readouterr().out)
    assert show_payload["status"] == "OK"
    assert show_payload["manifest"]["snapshot_id"] == created["snapshot_id"]


