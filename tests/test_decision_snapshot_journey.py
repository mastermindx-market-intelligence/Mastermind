# Journey 5: a forged stored byte is corrupt, and the CLI says so typed
# ---------------------------------------------------------------------------

def test_forged_snapshot_digest_is_corrupt(journey_root, capsys):
    _stage_book()
    created = snapshots.create_snapshot(
        "autonomous", decision_cutoff=_CUTOFF, recorded_at=_RECORDED,
    )
    path = snapshots._snapshot_path("autonomous", created["snapshot_id"])
    raw = path.read_bytes()
    # Flip exactly one byte inside the stored snapshot_id digest: still canonical-looking
    # JSON, but it can never re-verify against the recomputed content digest.
    marker = b'"snapshot_id":"sha256:'
    flip_index = raw.index(marker) + len(marker)
    flipped = b"0" if raw[flip_index:flip_index + 1] != b"0" else b"1"
    path.unlink()
    path.write_bytes(raw[:flip_index] + flipped + raw[flip_index + 1:])

    with pytest.raises(snapshots.SnapshotCorrupt):
        snapshots.load_snapshot("autonomous", created["snapshot_id"])

    # CLI: corrupt is a typed error on stderr, exit 1, and no snapshot body on stdout.
    assert cli.main([
        "show", "--book", "autonomous", "--snapshot-id", created["snapshot_id"],
    ]) == 1
    captured = capsys.readouterr()
    assert captured.out == ""
    assert "corrupt_snapshot" in captured.err

    # Companion exit-code check: an absent snapshot is the other typed 1 (not_found).
    missing_id = "sha256:" + "e" * 64
    assert cli.main(["show", "--book", "autonomous", "--snapshot-id", missing_id]) == 1
    captured = capsys.readouterr()
    assert captured.out == ""
    assert "not_found" in captured.err


