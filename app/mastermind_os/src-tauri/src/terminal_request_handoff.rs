//! A selected request is resolved against the private Terminal owner's fresh feed.
//! This module owns only fixed URL syntax and a single navigation request.
use serde::{Deserialize, Serialize};
use serde_json::Value;

const ERROR: &str = "TERMINAL_SHARING_HANDOFF_UNAVAILABLE";

#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RequestSelection {
    pub request_ref: String,
    pub revision: u8,
    pub delivery_id: String,
    pub content_sha256: String,
}

#[derive(Serialize)]
pub struct RequestHandoffReceipt {
    schema: &'static str,
    request_ref: String,
    revision: u8,
    delivery_id: String,
    outcome: &'static str,
}

fn canonical_uuid(value: &str) -> bool {
    // Reuse the incumbent exact lower-case UUID grammar without any opener.
    crate::terminal_handoff::sharing_review_url(value).is_ok()
}

fn valid_selection(selected: &RequestSelection) -> bool {
    selected.revision == 1
        && canonical_uuid(&selected.request_ref)
        && canonical_uuid(&selected.delivery_id)
        && selected.content_sha256.len() == 64
        && selected
            .content_sha256
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// `feed` must come from the private Terminal owner's guarded fixed reader,
/// never from Tauri arguments. That owner authenticates its own Terminal session
/// and checks viewer scopes/currentness. A UUID supplied alone is insufficient.
pub fn selected_review_url(
    selected: &RequestSelection,
    feed: &Value,
) -> Result<String, &'static str> {
    if !valid_selection(selected)
        || feed.get("schema").and_then(Value::as_str)
            != Some("mastermind.terminal_sharing_request_feed.v1")
    {
        return Err(ERROR);
    }
    let rows = feed
        .get("requests")
        .and_then(Value::as_array)
        .ok_or(ERROR)?;
    let matches: Vec<_> = rows
        .iter()
        .filter(|row| {
            row.get("request_ref").and_then(Value::as_str) == Some(selected.request_ref.as_str())
        })
        .collect();
    if matches.len() != 1 {
        return Err(ERROR);
    }
    let row = matches[0];
    if row.get("revision").and_then(Value::as_u64) != Some(1)
        || row.pointer("/delivery/delivery_id").and_then(Value::as_str)
            != Some(selected.delivery_id.as_str())
        || row
            .pointer("/delivery/content_sha256")
            .and_then(Value::as_str)
            != Some(selected.content_sha256.as_str())
        || row.pointer("/review/request_ref").and_then(Value::as_str)
            != Some(selected.request_ref.as_str())
        || row.pointer("/review/revision").and_then(Value::as_u64) != Some(1)
        || row.pointer("/review/delivery_id").and_then(Value::as_str)
            != Some(selected.delivery_id.as_str())
    {
        return Err(ERROR);
    }
    let base =
        crate::terminal_handoff::sharing_review_url(&selected.delivery_id).map_err(|_| ERROR)?;
    Ok(format!(
        "{base}?request={}&revision=1",
        selected.request_ref
    ))
}

/// A returned receipt means only one opener accepted a navigation request.
/// It never establishes browser arrival, Terminal identity, access or sharing.
pub fn request_review<F>(
    selected: &RequestSelection,
    feed: &Value,
    open: F,
) -> Result<RequestHandoffReceipt, &'static str>
where
    F: FnOnce(&str) -> Result<(), ()>,
{
    let url = selected_review_url(selected, feed)?;
    open(&url).map_err(|_| ERROR)?;
    Ok(RequestHandoffReceipt {
        schema: "mastermind.terminal_sharing_handoff.v1",
        request_ref: selected.request_ref.clone(),
        revision: 1,
        delivery_id: selected.delivery_id.clone(),
        outcome: "HANDOFF_REQUESTED",
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    const REQUEST: &str = "11111111-1111-4111-8111-111111111111";
    const DELIVERY: &str = "22222222-2222-4222-8222-222222222222";
    fn selection() -> RequestSelection {
        RequestSelection {
            request_ref: REQUEST.into(),
            revision: 1,
            delivery_id: DELIVERY.into(),
            content_sha256: "a".repeat(64),
        }
    }
    fn feed() -> Value {
        json!({"schema":"mastermind.terminal_sharing_request_feed.v1","requests":[{
            "request_ref":REQUEST,"revision":1,"delivery":{"delivery_id":DELIVERY,"content_sha256":"a".repeat(64)},
            "review":{"request_ref":REQUEST,"revision":1,"delivery_id":DELIVERY}
        }]})
    }
    #[test]
    fn actual_postgres_explicit_request_fixture_joins_selected_native_handoff() {
        // Generated by Terminal's inert PostgreSQL explicit-issuance/current-feed test.
        // This is source composition proof, not a live request or grant.
        let feed: Value = serde_json::from_str(include_str!(
            "../../src/inbox/fixtures/terminal-sharing-request-feed.json"
        ))
        .unwrap();
        let row = &feed["requests"][0];
        let selected = RequestSelection {
            request_ref: row["request_ref"].as_str().unwrap().into(),
            revision: 1,
            delivery_id: row["delivery"]["delivery_id"].as_str().unwrap().into(),
            content_sha256: row["delivery"]["content_sha256"].as_str().unwrap().into(),
        };
        let mut calls = 0;
        let receipt=request_review(&selected,&feed,|url|{
            calls+=1; assert_eq!(url,"https://app.mastermind-x.com/briefs/40000000-0000-4000-8000-000000000001/sharing?request=60000000-0000-4000-8000-000000000001&revision=1"); Ok(())
        }).unwrap();
        assert_eq!(calls, 1);
        assert_eq!(
            serde_json::to_value(receipt).unwrap()["outcome"],
            "HANDOFF_REQUESTED"
        );
        let mut changed = selected.clone();
        changed.content_sha256 = "f".repeat(64);
        assert!(selected_review_url(&changed, &feed).is_err());
    }

    #[test]
    fn exact_request_review_opens_once_and_claims_navigation_only() {
        let mut calls = Vec::new();
        let receipt = request_review(&selection(), &feed(), |url| {
            calls.push(url.to_owned());
            Ok(())
        })
        .unwrap();
        assert_eq!(calls,vec![format!("https://app.mastermind-x.com/briefs/{DELIVERY}/sharing?request={REQUEST}&revision=1")]);
        let value = serde_json::to_value(receipt).unwrap();
        assert_eq!(
            value,
            json!({"schema":"mastermind.terminal_sharing_handoff.v1","request_ref":REQUEST,
            "revision":1,"delivery_id":DELIVERY,"outcome":"HANDOFF_REQUESTED"})
        );
    }
    #[test]
    fn absent_changed_or_ambiguous_request_has_zero_opener_calls() {
        let original = feed();
        let mut cases = vec![
            json!({}),
            json!({"schema":"mastermind.terminal_sharing_request_feed.v1","requests":[]}),
        ];
        for pointer in [
            "/requests/0/revision",
            "/requests/0/delivery/delivery_id",
            "/requests/0/delivery/content_sha256",
            "/requests/0/review/request_ref",
            "/requests/0/review/revision",
            "/requests/0/review/delivery_id",
        ] {
            let mut changed = original.clone();
            *changed.pointer_mut(pointer).unwrap() = json!("changed");
            cases.push(changed);
        }
        let mut duplicate = original.clone();
        duplicate["requests"]
            .as_array_mut()
            .unwrap()
            .push(original["requests"][0].clone());
        cases.push(duplicate);
        for case in cases {
            let mut calls = 0;
            assert!(request_review(&selection(), &case, |_| {
                calls += 1;
                Ok(())
            })
            .is_err());
            assert_eq!(calls, 0);
        }
    }
    #[test]
    fn untrusted_selector_and_opener_failure_never_retry() {
        for bad in [
            "https://evil.example",
            "../other",
            "11111111-1111-4111-8111-111111111111?x=1",
            "11111111-1111-4111-8111-111111111111#fragment",
        ] {
            let mut selected = selection();
            selected.request_ref = bad.into();
            let mut calls = 0;
            assert!(request_review(&selected, &feed(), |_| {
                calls += 1;
                Ok(())
            })
            .is_err());
            assert_eq!(calls, 0);
        }
        let mut calls = 0;
        assert!(request_review(&selection(), &feed(), |_| {
            calls += 1;
            Err(())
        })
        .is_err());
        assert_eq!(calls, 1);
        let raw = json!({"request_ref":REQUEST,"revision":1,"delivery_id":DELIVERY,"content_sha256":"a".repeat(64),"url":"https://evil.example"});
        assert!(serde_json::from_value::<RequestSelection>(raw).is_err());
    }
}
